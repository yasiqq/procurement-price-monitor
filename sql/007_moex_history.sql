CREATE TABLE IF NOT EXISTS raw.moex_history (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BOARDID TEXT,
    TRADEDATE TEXT NOT NULL,
    SHORTNAME TEXT,
    SECID TEXT NOT NULL,
    OPEN TEXT,
    LOW TEXT,
    HIGH TEXT,
    CLOSE TEXT,
    NUMTRADES TEXT,
    WAPRICE TEXT,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (TRADEDATE, SECID)
);